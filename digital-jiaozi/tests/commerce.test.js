test('并发余额/最后库存、资格、刷新码失效、取消/到期/核销互斥和退款一次',async t=>{
  const h=await harness(t);h.init();h.init('demo-b');const c=h.m.commerce;
  for(const user of ['demo-a','demo-b']){h.event('purchase.verified',{merchantId:'merchant-1',orderId:randomUUID()},user);h.event('purchase.verified',{merchantId:'merchant-2',orderId:randomUUID()},user);}
  assert.throws(()=>c.createOrder('demo-a',activity,'physical-card',randomUUID()),e=>e.code==='QUALIFICATION_REQUIRED');
  h.m.repo.run("UPDATE dj_rewards SET stock=1 WHERE id='magnet'");
  const results=await Promise.all(['demo-a','demo-b'].map(user=>h.call(`/activities/${activity}/redemptions`,'POST',{rewardItemId:'magnet'},user,key())));
  assert.equal(results.filter(r=>r.status===200).length,1);assert.equal(results.find(r=>r.status!==200).code,'OUT_OF_STOCK');
  const winner=results[0].status===200?'demo-a':'demo-b',loser=winner==='demo-a'?'demo-b':'demo-a',id=results.find(r=>r.status===200).data.id;
  assert.equal(c.wallet(winner,activity).available,20);assert.equal(c.wallet(loser,activity).available,140);
  const token=c.token(winner,id),fresh=c.token(winner,id);assert.throws(()=>c.staffToken(staff,token.token),e=>e.code==='TOKEN_INVALID');
  h.now+=300001;assert.throws(()=>c.staffToken(staff,fresh.token),e=>e.code==='TOKEN_EXPIRED');assert.equal(c.order(winner,id).status,'PENDING');
  const current=c.token(winner,id);
  const competing=await Promise.all([h.call(`/redemptions/${id}/cancel`,'POST',{},winner),h.call('/staff/redemptions/verify','POST',{token:current.token},'staff')]);
  const final=c.order(winner,id).status;assert.ok(['CANCELLED','REDEEMED'].includes(final));
  assert.equal(c.wallet(winner,activity).available,final==='CANCELLED'?140:20);
  assert.equal(h.m.repo.one('SELECT COUNT(*) n FROM dj_ledger WHERE dedup=?',`refund:${id}`).n,final==='CANCELLED'?1:0);
  assert.ok(competing.some(r=>r.status===200));
  const balance=await Promise.all(['magnet','postcard'].map(rewardItemId=>h.call(`/activities/${activity}/redemptions`,'POST',{rewardItemId},loser,key())));
  assert.ok(balance.filter(r=>r.status===200).length===1);
  const pending=balance.find(r=>r.status===200).data,expiryToken=c.token(loser,pending.id);h.now=pending.expires_at;
  await Promise.all([h.call(`/redemptions/${pending.id}/cancel`,'POST',{},loser),h.call('/staff/redemptions/verify','POST',{token:expiryToken.token},'staff'),h.call(`/redemptions/${pending.id}`,'GET',undefined,loser)]);
  c.expire();c.cancel(loser,pending.id);assert.equal(c.order(loser,pending.id).status,'EXPIRED');assert.equal(c.wallet(loser,activity).available,140);assert.equal(c.wallet(loser,activity).lifetime,140);
  assert.equal(h.m.repo.one('SELECT COUNT(*) n FROM dj_ledger WHERE dedup=?',`refund:${pending.id}`).n,1);
});
